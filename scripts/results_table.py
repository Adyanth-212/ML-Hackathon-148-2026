"""Write RESULTS.md: every model and pipeline we tried, with its accuracy, in one place.

    python scripts/results_table.py

Reads experiments/results/{model_comparison,pipeline_summary,hmm_comparison,tuning_comparison}.csv,
so the numbers are always the ones the scripts produced.
"""
from __future__ import annotations

import sys

import pandas as pd

from pathsnap.config import repo_path

OWNER = {"advitha": "Advitha", "adyanth": "Adyanth", "sudhe": "Sudhe", "tilak": "Tilak"}
NICE = {
    "advitha_lgbm_tuned": "LightGBM (Bayesian-tuned) ⭐ selected",
    "advitha_lgbm": "LightGBM",
    "advitha_xgb": "XGBoost",
    "advitha_hgb": "HistGradientBoosting",
    "sudhe_random_forest": "Random Forest",
    "sudhe_extra_trees": "Extra Trees",
    "sudhe_decision_tree": "Decision Tree",
    "adyanth_logreg": "Logistic Regression",
    "adyanth_sgd": "SGD (logistic loss)",
    "adyanth_gnb": "Gaussian Naive Bayes",
}


def pct(x) -> str:
    return "–" if pd.isna(x) else f"{100 * x:.1f}%"


def num(x, d=3) -> str:
    return "–" if pd.isna(x) else f"{x:.{d}f}"


def md(df: pd.DataFrame) -> str:
    head = "| " + " | ".join(df.columns) + " |\n|" + "|".join("---" for _ in df.columns) + "|\n"
    return head + "\n".join("| " + " | ".join(str(v) for v in r) + " |" for r in df.itertuples(index=False))


def main() -> int:
    res = repo_path("experiments/results")
    comp = pd.read_csv(res / "model_comparison.csv")
    comp = comp[~comp.is_ablation.fillna(False).astype(bool)]
    ml = comp[comp.cv_macro_f1_mean.notna()].sort_values("student_test_top1", ascending=False)
    rules = comp[comp.cv_macro_f1_mean.isna()]
    pipe = pd.read_csv(res / "pipeline_summary.csv").set_index("variant")
    hmm = pd.read_csv(res / "hmm_comparison.csv")
    tune = pd.read_csv(res / "tuning_comparison.csv").set_index("metric")

    models = pd.DataFrame({
        "#": range(1, len(ml) + 1),
        "Model": [NICE.get(m, m) for m in ml.model],
        "Family": ml.family.str.replace("gradient boosting", "boosting"),
        "By": [OWNER.get(m.split("_")[0], "") for m in ml.model],
        "Test Top-1 (accuracy)": [f"**{pct(v)}**" for v in ml.student_test_top1],
        "Test macro F1": [num(v) for v in ml.student_test_macro_f1],
        "Test log loss": [num(v) for v in ml.student_test_log_loss],
        "CV Top-1": [pct(v) for v in ml.cv_top1_mean],
        "CV macro F1 (± std)": [f"{m:.3f} ± {s:.3f}" for m, s in zip(ml.cv_macro_f1_mean, ml.cv_macro_f1_std)],
        "Fit time": [f"{v:.0f} s" for v in ml.fit_seconds],
        "Inference / trip": [f"{v:.0f} ms" if v >= 1 else f"{v:.1f} ms" for v in ml.inference_ms_per_trip],
    })
    rule_rows = pd.DataFrame({
        "Rule (no learning)": ["Nearest arc", "Nearest arc + heading penalty"],
        "Test Top-1": [pct(rules.set_index("model").student_test_top1.get(k)) for k in
                       ("rule_nearest_arc", "rule_nearest_heading")],
    })
    final = pd.DataFrame({
        "Stage": ["Rule baseline (nearest arc + heading)", "Tuned LightGBM, classifier only",
                  "**Tuned LightGBM + HMM/Viterbi (final, what the API serves)**"],
        "Test Top-1 (accuracy)": [pct(pipe.loc[v, "top1"]) for v in ("baseline_rule", "model")]
        + [f"**{pct(pipe.loc['model_hmm', 'top1'])}**"],
        "Route continuity": [num(pipe.loc[v, "continuity_mean"]) for v in ("baseline_rule", "model", "model_hmm")],
        "Route breaks": [f"{int(pipe.loc[v, 'breaks_total']):,}" for v in ("baseline_rule", "model", "model_hmm")],
        "Time / trip": [f"{pipe.loc[v, 'total_ms_mean'] / 1000:.2f} s" for v in ("baseline_rule", "model", "model_hmm")],
    })
    h = pd.DataFrame({
        "Decoder": hmm.variant,
        "Test Top-1": [pct(v) for v in hmm.top1],
        "Continuity": [num(v) for v in hmm.continuity_mean],
        "Route F1": [num(v) for v in hmm.route_f1_mean],
    })
    t = pd.DataFrame({
        "": ["CV Top-1", "Test Top-1", "Test macro F1", "Test log loss", "Inference / trip"],
        "Untuned LightGBM": [pct(tune.loc["CV Top-1 (mean)", "untuned"]), pct(tune.loc["Top-1", "untuned"]),
                             num(tune.loc["macro F1", "untuned"]), num(tune.loc["log loss", "untuned"], 4),
                             f"{tune.loc['inference (ms per trip)', 'untuned']:.0f} ms"],
        "Bayesian-tuned": [pct(tune.loc["CV Top-1 (mean)", "tuned"]), pct(tune.loc["Top-1", "tuned"]),
                           num(tune.loc["macro F1", "tuned"]), num(tune.loc["log loss", "tuned"], 4),
                           f"{tune.loc['inference (ms per trip)', 'tuned']:.0f} ms"],
    })

    text = f"""# Results

**Final pipeline accuracy: {pct(pipe.loc['model_hmm', 'top1'])} of GPS points matched to the correct road** on the 10 held-out
student-test trips (Bayesian-tuned LightGBM + HMM/Viterbi decoder). Generated by `python scripts/results_table.py`
from `experiments/results/`; full write-up in [`report/team_187.pdf`](report/team_187.pdf).

*Top-1 (accuracy)* = share of GPS points whose predicted road arc is the correct one (the primary metric).
*Test* = the 10 student-test trips, never used for training or tuning. *CV* = 5-fold cross-validation grouped by
trip on the 80 training trips. Macro F1 and log loss are at the candidate level.

## End to end (the full system)

{md(final)}

## All {len(ml)} classifiers (same features, folds and test set for every model)

{md(models)}

{md(rule_rows)}

## Bayesian hyperparameter optimisation (40 Optuna trials on LightGBM)

{md(t)}

## HMM decoder (classifier = tuned LightGBM)

{md(h)}
"""
    out = repo_path("RESULTS.md")
    out.write_text(text)
    print(f"wrote {out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
